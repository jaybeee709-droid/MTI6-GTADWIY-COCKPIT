/* Generates src/security-posture-data.ts MECHANICALLY from the
 * proxy source (netlify/functions/mti6-proxy.mjs): the action
 * allowlist and provider list the proxy itself declares in its
 * gateway.status response, and the NAMES of the environment
 * variables it reads. Values are never read — the script extracts
 * identifiers only, and asserts no extracted string looks like a
 * credential value. Run:
 *   node scripts/generate-security-posture.mjs
 * It asserts the POST-only gate exists and the allowlist is the
 * recorded five actions. */
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('netlify/functions/mti6-proxy.mjs', 'utf8');

function extractStringArray(source, key) {
  const m = source.match(new RegExp(`${key}:\\s*\\[([^\\]]*)\\]`));
  if (!m) throw new Error(`proxy: ${key} array not found`);
  return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
}

const actions = extractStringArray(src, 'actions');
const providers = extractStringArray(src, 'providers');

const envNames = [...new Set([...src.matchAll(/(?:process\.env|env)\.([A-Z][A-Z0-9_]+)/g)].map((m) => m[1]))].sort();

if (!/METHOD_NOT_ALLOWED", "POST required\."/.test(src)) {
  throw new Error('proxy: POST-only gate not found — posture facts changed, review before generating');
}
const expectedActions = ['gateway.ping', 'gateway.status', 'geo.geocode', 'market.prices', 'star.chat', 'transit.departures', 'transit.stopsNear'];
if (JSON.stringify([...actions].sort()) !== JSON.stringify(expectedActions)) {
  throw new Error(`proxy allowlist changed: ${JSON.stringify(actions)} — owner review before regenerating`);
}
for (const v of [...actions, ...providers, ...envNames]) {
  if (v.length > 64 || /\s/.test(v)) throw new Error(`suspicious extracted value: ${v}`);
}

const out = `/* GENERATED by scripts/generate-security-posture.mjs from
 * netlify/functions/mti6-proxy.mjs — do not edit by hand. These are
 * the proxy's own declared facts: its action allowlist, its
 * provider list, and the NAMES of the environment variables it
 * reads. Secret VALUES live only in the Netlify environment and
 * never appear in this repository or this file. */
export const PROXY_ACTIONS: string[] = ${JSON.stringify(actions)};
export const PROXY_PROVIDERS: string[] = ${JSON.stringify(providers)};
export const PROXY_ENV_NAMES: string[] = ${JSON.stringify(envNames)};
export const PROXY_METHOD = 'POST' as const;
`;

writeFileSync('src/security-posture-data.ts', out);
console.log(`security-posture-data.ts: actions ${JSON.stringify(actions)}, providers ${JSON.stringify(providers)}, env names ${JSON.stringify(envNames)}`);
