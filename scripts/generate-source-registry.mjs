/* Generates src/source-registry-data.ts from the canonical
 * keyless discovery catalog in js/discovery-bots.js
 * (KEYLESS_DISCOVERY_SOURCES). Mechanical extraction only — the
 * frozen/governed source file is read, never edited. Run:
 *   node scripts/generate-source-registry.mjs
 * Source Registry v1 (v188): the app's read model of every
 * registered keyless source. Candidates in the Resource Engine
 * stay DISCOVERED/UNVERIFIED until the owner's gate decides;
 * this file only mirrors the catalog for display. */
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const src = readFileSync(new URL('../js/discovery-bots.js', import.meta.url), 'utf8');
const sandbox = { window: {}, console };
vm.createContext(sandbox);
vm.runInContext(src, sandbox);
const bots = sandbox.window.MTI6DiscoveryBots;
if (!bots || !Array.isArray(bots.KEYLESS_DISCOVERY_SOURCES)) {
  throw new Error('KEYLESS_DISCOVERY_SOURCES not found in js/discovery-bots.js');
}
const sources = bots.KEYLESS_DISCOVERY_SOURCES.map((s) => ({
  id: s.id,
  name: s.name,
  provider: s.provider,
  category: s.category,
  endpoint: s.endpointPattern,
  provides: s.provides ?? [],
  probedAt: s.probedAt ?? null,
}));
const out = `/* GENERATED by scripts/generate-source-registry.mjs from
 * js/discovery-bots.js (KEYLESS_DISCOVERY_SOURCES) — do not edit
 * by hand. Source Registry v1 (v188). */

export interface RegisteredSource {
  id: string;
  name: string;
  provider: string;
  category: string;
  endpoint: string;
  provides: string[];
  probedAt: string | null;
}

export const REGISTERED_SOURCES: RegisteredSource[] = ${JSON.stringify(sources, null, 2)};

export const SOURCE_REGISTRY_EXCLUSIONS: string[] = [
  'DefiLlama Bridges — 402, paid plan (probed 2026-11-24)',
  'L2Beat API — 401, key required (probed 2026-11-24)',
  'Birdeye — 401, key required (probed 2026-11-24)',
  'Solscan public API — 404, deprecated (probed 2026-11-24)',
  'Tally / yDaemon / Jupiter / mempool.space — unreachable from the build environment, unverified (probed 2026-11-24)',
  'Gnosis Blockscout — bot-walled from the build environment, unverified (probed 2026-11-24)',
  'Wormhole W contract — candidate address resolved to a different token on two sources (2026-11-24)',
  'ARB / OP contracts — one source only, UNVERIFIED by the support model (2026-11-24)',
];
`;
writeFileSync(new URL('../src/source-registry-data.ts', import.meta.url), out);
console.log(`source-registry-data.ts written: ${sources.length} sources`);
