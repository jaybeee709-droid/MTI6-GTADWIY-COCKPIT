/* Generates src/resource-catalog-data.ts MECHANICALLY from the
 * frozen Resource Engine seed file (js/data/resource-seeds.js) —
 * the 52 governed provider records of FREE-RESOURCE-CATALOG.md
 * (2026-11-16) plus its 6 recorded capability gaps.
 *
 * The frozen seeds are never edited — this script only reads them.
 * Nothing is retyped: every field in the output is copied from the
 * seed records. Credential VALUES never exist in the seeds (the
 * schema records existence and custody only), so none can appear
 * here. Run:
 *   node scripts/generate-resource-catalog.mjs
 * It asserts the catalog counts (52 candidates: CONNECTED 12,
 * TESTED 16, RESEARCHING 20, PREPARED 2, DISCOVERED 2; 6 gaps). */
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(readFileSync('js/data/resource-seeds.js', 'utf8'), sandbox);
const seeds = sandbox.window.ResourceSeeds;
if (!seeds || !Array.isArray(seeds.candidates) || !Array.isArray(seeds.gaps)) {
  throw new Error('js/data/resource-seeds.js: ResourceSeeds {candidates, gaps} not found');
}

const providers = seeds.candidates.map((r) => ({
  id: r.id,
  name: r.name,
  provider: r.provider,
  domain: r.domain,
  resourceType: r.resourceType,
  capabilities: Array.isArray(r.capabilities) ? r.capabilities : [],
  stage: r.pipelineStage,
  costState: r.freeState,
  credentialState: r.credentialState,
  ownerApprovalState: r.ownerApprovalState,
  fallbackRole: typeof r.fallbackRole === 'string' ? r.fallbackRole : null,
}));

const gaps = seeds.gaps.map((g) => ({
  id: g.id,
  capability: g.capability,
  title: g.title,
  status: typeof g.status === 'string' ? g.status : 'OPEN',
}));

const byStage = {};
for (const p of providers) byStage[p.stage] = (byStage[p.stage] ?? 0) + 1;

const expected = { CONNECTED: 12, TESTED: 16, RESEARCHING: 20, PREPARED: 2, DISCOVERED: 2 };
for (const [stage, n] of Object.entries(expected)) {
  if (byStage[stage] !== n) throw new Error(`stage ${stage}: expected ${n}, got ${byStage[stage] ?? 0}`);
}
if (providers.length !== 52) throw new Error(`expected 52 candidates, got ${providers.length}`);
if (gaps.length !== 6) throw new Error(`expected 6 gaps, got ${gaps.length}`);

const secretShaped = /(apikey|apisecret|password|accesstoken|refreshtoken|bearertoken|privatekey|seedphrase)/i;
const serialized = JSON.stringify({ providers, gaps });
for (const p of providers) {
  for (const k of Object.keys(p)) {
    if (secretShaped.test(k)) throw new Error(`secret-shaped key in output record: ${k}`);
  }
}
if (serialized.includes('credentialValue')) throw new Error('credential value field leaked into output');

const out = `/* GENERATED by scripts/generate-resource-catalog.mjs from the
 * frozen js/data/resource-seeds.js — do not edit by hand. Records
 * are governance records: stage, exact cost class, credential
 * EXISTENCE/custody only (never a value), owner approval state.
 * CONNECTED means wired per the connection evidence recorded in
 * the canonical store; this module wires nothing. */
export interface ResourceProvider {
  id: string;
  name: string;
  provider: string;
  domain: string;
  resourceType: string;
  capabilities: string[];
  stage: string;
  costState: string;
  credentialState: string;
  ownerApprovalState: string;
  fallbackRole: string | null;
}
export interface ResourceGap {
  id: string;
  capability: string;
  title: string;
  status: string;
}
export const RESOURCE_PROVIDERS: ResourceProvider[] = ${JSON.stringify(providers, null, 1)};
export const RESOURCE_GAPS: ResourceGap[] = ${JSON.stringify(gaps, null, 1)};
export const RESOURCE_COUNTS = { total: ${providers.length}, byStage: ${JSON.stringify(byStage)}, gaps: ${gaps.length} } as const;
`;

writeFileSync('src/resource-catalog-data.ts', out);
console.log(`resource-catalog-data.ts: ${providers.length} providers, stages ${JSON.stringify(byStage)}, ${gaps.length} gaps`);
