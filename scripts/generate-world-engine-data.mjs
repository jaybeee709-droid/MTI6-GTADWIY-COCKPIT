/* Generates src/world-engine-data.ts by RUNNING the canonical
 * World Engine (js/world-engine.js, buildGraph) over a snapshot
 * assembled from the frozen sources:
 *   cryptoRecords — the 826 encyclopedia records (Batch A families,
 *     Canonical 60, Batch B) + the 48 frozen entity records;
 *   principals — the canonical 12 from js/tribe-principals.js;
 *   angels — the APPROVED identities from js/angel-identities.js.
 * Every other snapshot part (assets / networks / protocols
 * intelligence views, wallets, opportunities, positions,
 * assignments, risk profiles, cost records, alerts) is runtime or
 * session data and is intentionally EMPTY in this frozen run —
 * the output states that scope wherever it is shown.
 *
 * Nothing is retyped: the counts below are the engine's own
 * stats over that snapshot, computed at generation time. An
 * unresolved reference is counted by the engine, never promoted
 * into a node. Run:
 *   node scripts/generate-world-engine-data.mjs
 * It asserts the frozen input counts (826 + 48 records, 12
 * principals, 4 approved angels). */
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

function loadInto(sandbox, path) {
  vm.runInContext(readFileSync(path, 'utf8'), sandbox);
}
function makeSandbox() {
  const sandbox = { window: {}, console };
  vm.createContext(sandbox);
  return sandbox;
}

// Encyclopedia + entity records (each file in its own sandbox,
// mirroring generate-encyclopedia-data.mjs / generate-entity-data.mjs).
function loadRecords(path, globalName) {
  const sandbox = makeSandbox();
  loadInto(sandbox, path);
  const data = sandbox.window[globalName];
  if (!data || !Array.isArray(data.records)) throw new Error(`${path}: ${globalName}.records not found`);
  return data.records;
}
const encyclopedia = [
  ...loadRecords('js/data/encyclopedia-batch-a.js', 'EncyclopediaBatchA'),
  ...loadRecords('js/data/encyclopedia-canonical-60.js', 'EncyclopediaCanonical60'),
  ...loadRecords('js/data/encyclopedia-batch-b.js', 'EncyclopediaBatchB'),
];
const entities = [
  ...loadRecords('js/data/entity-batch-1.js', 'EncyclopediaEntityBatch1'),
  ...loadRecords('js/data/entity-batch-2.js', 'EncyclopediaEntityBatch2'),
];

// Principals + angels + the engine itself share one sandbox.
const world = makeSandbox();
loadInto(world, 'js/tribe-principals.js');
loadInto(world, 'js/angel-identities.js');
loadInto(world, 'js/world-engine.js');
const principals = world.window.TribePrincipals.listPrincipals();
const angels = world.window.AngelIdentities.listApproved().map((a) => ({ id: a.id, name: a.displayName }));
const WorldEngine = world.window.WorldEngine;
if (!WorldEngine || typeof WorldEngine.buildGraph !== 'function') throw new Error('WorldEngine.buildGraph not found');

if (encyclopedia.length !== 826) throw new Error(`expected 826 encyclopedia records, got ${encyclopedia.length}`);
if (entities.length !== 48) throw new Error(`expected 48 entity records, got ${entities.length}`);
if (principals.length !== 12) throw new Error(`expected 12 principals, got ${principals.length}`);
if (angels.length !== 4) throw new Error(`expected 4 approved angels, got ${angels.length}`);

const graph = WorldEngine.buildGraph({
  cryptoRecords: [...encyclopedia, ...entities],
  principals,
  angels,
});
const stats = graph.stats;
const unresolvedSample = graph.unresolved.slice(0, 12).map((u) => ({ from: u.from, ref: u.ref, type: u.type }));

const out = `/* GENERATED by scripts/generate-world-engine-data.mjs — do not
 * edit by hand. The canonical World Engine (js/world-engine.js)
 * run over the frozen canonical records (826 encyclopedia + 48
 * entities), the 12 principals, and the 4 approved angel
 * identities. Runtime record kinds (opportunities, positions,
 * assignments, profiles, costs, alerts, wallets, intelligence
 * views) are owner/session data and are NOT in this frozen run —
 * in the live app they join the graph as they are recorded. */
export const WORLD_ENGINE_STATS = ${JSON.stringify(
  {
    nodeCount: stats.nodeCount,
    edgeCount: stats.edgeCount,
    unresolvedCount: stats.unresolvedCount,
    byKind: Object.fromEntries(Object.entries(stats.byKind).filter(([, n]) => n > 0)),
    byEdgeType: Object.fromEntries(Object.entries(stats.byEdgeType).filter(([, n]) => n > 0)),
  },
  null,
  1,
)} as const;
export const WORLD_ENGINE_UNRESOLVED_SAMPLE: { from: string; ref: string; type: string }[] = ${JSON.stringify(unresolvedSample, null, 1)};
`;

writeFileSync('src/world-engine-data.ts', out);
console.log(
  `world-engine-data.ts: ${stats.nodeCount} nodes, ${stats.edgeCount} edges, ${stats.unresolvedCount} unresolved; kinds ${JSON.stringify(stats.byKind)}; edges ${JSON.stringify(stats.byEdgeType)}`,
);
