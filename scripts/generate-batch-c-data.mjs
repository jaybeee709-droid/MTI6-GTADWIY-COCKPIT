/* MTI6-GTADWIY-COCKPIT — Batch C React candidate data.
 * Reads the frozen-candidate artifact (js/data/encyclopedia-
 * batch-c.js) and the frozen Batch B file (for parent titles)
 * and emits src/batch-c-data.ts: the count, the artifact
 * SHA-256, and a small sample for the Encyclopedia screen's
 * BATCH C panel. The candidate set is NOT merged into
 * src/encyclopedia-data.ts — the canonical index stays 826
 * until the owner's review pass and a separate import. */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import vm from 'node:vm';

function loadBatch(path, key) {
  const ctx = { window: {} };
  vm.createContext(ctx);
  vm.runInContext(readFileSync(new URL(path, import.meta.url), 'utf8'), ctx);
  return ctx.window[key];
}

const batchCFile = readFileSync(
  new URL('../js/data/encyclopedia-batch-c.js', import.meta.url),
  'utf8',
);
const sha = createHash('sha256').update(batchCFile).digest('hex');
const batchC = loadBatch('../js/data/encyclopedia-batch-c.js', 'EncyclopediaBatchC');
const batchB = loadBatch('../js/data/encyclopedia-batch-b.js', 'EncyclopediaBatchB');
const titleById = new Map(batchB.records.map((r) => [r.id, r.title]));
const samples = batchC.records.slice(0, 8).map((a) => ({
  title: a.title,
  strategy: titleById.get(a.parentRef) ?? a.parentRef,
}));

const out = `/* GENERATED by scripts/generate-batch-c-data.mjs from the
 * frozen-candidate artifact js/data/encyclopedia-batch-c.js —
 * do not edit by hand. Batch C is NOT part of the canonical
 * encyclopedia index (826) until the owner's review pass and a
 * separate import action. */
export const BATCH_C_COUNT = ${batchC.records.length};
export const BATCH_C_SHA256 = '${sha}';
export const BATCH_C_SAMPLES: { title: string; strategy: string }[] = ${JSON.stringify(samples, null, 2)};
`;
writeFileSync(new URL('../src/batch-c-data.ts', import.meta.url), out);
console.log(`batch-c-data.ts: ${batchC.records.length} actions · sha ${sha.slice(0, 12)}…`);
