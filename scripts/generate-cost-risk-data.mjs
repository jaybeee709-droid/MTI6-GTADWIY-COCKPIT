/* Generates src/cost-risk-data.ts MECHANICALLY from the canonical
 * vanilla engines js/cost-intelligence.js and
 * js/risk-intelligence.js (both load in a bare vm by design).
 *
 * Only the engines' own exported vocabularies are copied: the 12
 * cost kinds with their labels and descriptions, the cost states,
 * the 19 canonical risk dimensions, the dimension states, the
 * subject types, the 3 D6-approved PENDING dimensions (Batch D
 * only — recorded as pending, never as usable keys), and the
 * spec→canonical reconciliation table. No amounts, no profiles,
 * no scores exist in this output because none are recorded in the
 * vocabularies. Run:
 *   node scripts/generate-cost-risk-data.mjs
 * It asserts the recorded counts (12 kinds / 19 dimensions /
 * 3 pending / 18 reconciliation rows). */
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const sandbox = {};
sandbox.globalThis = sandbox;
vm.createContext(sandbox);
vm.runInContext(readFileSync('js/cost-intelligence.js', 'utf8'), sandbox);
vm.runInContext(readFileSync('js/risk-intelligence.js', 'utf8'), sandbox);
const CI = sandbox.CostIntelligence;
const RI = sandbox.RiskIntelligence;
if (!CI || !RI) throw new Error('cost/risk engines did not load');

const costKinds = CI.COST_KINDS.map((kind) => {
  const d = CI.describeCostKind(kind);
  return { kind, label: d.label, description: d.description };
});
const reconciliation = RI.RECONCILIATION.map((r) => ({
  specDimension: r.specDimension,
  canonicalDimension: r.canonicalDimension ?? null,
  status: r.status,
}));

if (costKinds.length !== 12) throw new Error(`expected 12 cost kinds, got ${costKinds.length}`);
if (RI.RISK_DIMENSIONS.length !== 19) throw new Error(`expected 19 risk dimensions, got ${RI.RISK_DIMENSIONS.length}`);
if (RI.PENDING_DIMENSIONS.length !== 3) throw new Error(`expected 3 pending dimensions, got ${RI.PENDING_DIMENSIONS.length}`);
if (reconciliation.length !== 18) throw new Error(`expected 18 reconciliation rows, got ${reconciliation.length}`);
if (reconciliation.filter((r) => r.status === 'UNMAPPED').length !== 5)
  throw new Error('expected exactly 5 UNMAPPED reconciliation rows');

const out = `/* GENERATED by scripts/generate-cost-risk-data.mjs from
 * js/cost-intelligence.js + js/risk-intelligence.js — do not edit
 * by hand. Framework vocabularies only: no amounts (an UNKNOWN
 * cost is null, never zero), no risk scores (none exist anywhere
 * in the engines — score-shaped fields are rejected by them). */
export interface CostKind { kind: string; label: string; description: string }
export const COST_KINDS: CostKind[] = ${JSON.stringify(costKinds, null, 1)};
export const COST_STATES: string[] = ${JSON.stringify(CI.COST_STATES)};
export const RISK_DIMENSIONS: string[] = ${JSON.stringify(RI.RISK_DIMENSIONS)};
export const DIMENSION_STATES: string[] = ${JSON.stringify(RI.DIMENSION_STATES)};
export const RISK_SUBJECT_TYPES: string[] = ${JSON.stringify(RI.SUBJECT_TYPES)};
export const PENDING_DIMENSIONS: { code: string; status: string; note: string }[] = ${JSON.stringify(RI.PENDING_DIMENSIONS, null, 1)};
export const RISK_RECONCILIATION: { specDimension: string; canonicalDimension: string | null; status: string }[] = ${JSON.stringify(reconciliation, null, 1)};
`;

writeFileSync('src/cost-risk-data.ts', out);
console.log(`cost-risk-data.ts: ${costKinds.length} cost kinds, ${RI.RISK_DIMENSIONS.length} risk dimensions, ${RI.PENDING_DIMENSIONS.length} pending, ${reconciliation.length} reconciliation rows`);
