/** Entries owned by one bot: 'star' for STAR, or a Tribe
 *  principal id. Unknown ids return an empty list — never a
 *  guessed grouping. */
export function getRegistryForPrincipal(principalId: string): ApiRegistryEntry[] {
  return API_REGISTRY.filter((e) => e.assignedPrincipal === principalId);
}

/** One entry by id, or null when the id is not in the registry. */
export function getRegistryEntry(id: string): ApiRegistryEntry | null {
  return API_REGISTRY.find((e) => e.id === id) ?? null;
}

/** Entries whose fallback chain is actually WIRED in code today
 *  (not merely documented). */
export function getWiredFallbackEntries(): ApiRegistryEntry[] {
  return API_REGISTRY.filter((e) => e.fallbackOrder.length > 0 && e.fallbackWired);
}

/** Entries with no fallback at all — single source, honestly. */
export function getNoFallbackEntries(): ApiRegistryEntry[] {
  return API_REGISTRY.filter((e) => e.fallbackOrder.length === 0);
}
