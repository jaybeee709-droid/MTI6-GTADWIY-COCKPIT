export type ApiKeyStatus = 'CONFIGURED' | 'NOT_CONFIGURED';

/** Cost classes exactly as recorded in the Resource Engine
 *  catalog (FREE_OAUTH and SELF_HOSTABLE are catalog classes
 *  too — Mobility Database is OAuth, OSRM is self-hostable). */
export type ApiCostClass =
  | 'FREE_KEYLESS'
  | 'FREE_KEY_REQUIRED'
  | 'FREE_WITH_LIMITS'
  | 'FREE_OAUTH'
  | 'FREEMIUM'
  | 'PAID'
  | 'SELF_HOSTABLE'
  | 'UNKNOWN';

/** 'star' for STAR provider keys; otherwise a Tribe principal id
 *  from TRIBE_PRINCIPALS in worlds-data.ts. */
export type ApiAssignedPrincipal = string;

export interface ApiRegistryEntry {
  id: string;
  name: string;
  provider: string;
  /** Work domain, e.g. 'prices', 'transit', 'cameras'. */
  category: string;
  assignedPrincipal: ApiAssignedPrincipal;
  /** Env variable NAME only, or null when no key exists / the
   *  API is keyless. Never a value. */
  keyName: string | null;
  keyStatus: ApiKeyStatus;
  keyNote?: string;
  /** Monthly call cap as a number with a source, or 'UNKNOWN'. */
  monthlyLimit: number | 'UNKNOWN';
  /** Where the monthly figure came from; null when UNKNOWN. */
  monthlyLimitSource: string | null;
  monthlyLimitNote?: string;
  /** Fallback chain in order (provider names). Empty when none. */
  fallbackOrder: string[];
  /** True only when the chain is WIRED in code today. */
  fallbackWired: boolean;
  /** 'NO FALLBACK — single source' when fallbackOrder is empty,
   *  or a note on a documented-but-unwired chain. */
  fallbackNote?: string;
  /** Always 'UNKNOWN' — no usage metering exists in the app. */
  usage: 'UNKNOWN';
  usageNote: string;
  costClass: ApiCostClass;
  costNote?: string;
  /** Wired into the app or the proxy today (vs listed/planned). */
  wired: boolean;
  wiredNote?: string;
}

